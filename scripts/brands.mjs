// 真品牌标识：把「讲某个产品时用的是它自己的 logo」变成一条命令的事。
//   brands/library.json      —— 你维护的牌子清单（label / 文件名 / 文案里的各种叫法）
//   public/brands/*          —— 真图标文件（svg 或 ≥200px 的 png，透明底）
//   src/lib/brands.generated.ts —— 本脚本生成，只收录「文件真的在盘上」的条目
// 为什么要生成这一步：组件跑在浏览器里没法列目录，引用一个不存在的静态文件会让 Remotion 渲染失败。
// node scripts/brands.mjs sync    生成（出片前跑一次）
// node scripts/brands.mjs check   只看：哪些牌子还没放文件、哪些文件还没登记
// node scripts/brands.mjs missing 只列缺文件的牌子（给素材采集清单用）
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LIB = path.join(ROOT, "brands", "library.json");
const DIR = path.join(ROOT, "public", "brands");
const OUT = path.join(ROOT, "src", "lib", "brands.generated.ts");

const j = JSON.parse(fs.readFileSync(LIB, "utf8").replace(/^﻿/, ""));
const cmd = process.argv[2] || "check";

const entries = Object.entries(j.brands || {}).map(([key, b]) => ({
  key,
  label: b.label || key,
  file: b.file || `${key}.svg`,
  aliases: [key, ...(b.aliases || [])],
}));

// 0 字节的下载残片 / 空 svg 也算「没有」：上屏会渲成破图，比退成通用图标糟得多
const sizeOf = (e) => {
  const p = path.join(DIR, e.file);
  return fs.existsSync(p) ? fs.statSync(p).size : -1;
};
const has = (e) => sizeOf(e) > 120;
const live = entries.filter(has);
const missing = entries.filter((e) => !has(e));
const broken = entries.filter((e) => sizeOf(e) >= 0 && sizeOf(e) <= 120);

const IMG = /\.(svg|png|jpe?g|webp)$/i;
const unmapped = fs.existsSync(DIR) ? fs.readdirSync(DIR).filter((f) => IMG.test(f) && !entries.some((e) => e.file === f)) : [];

if (cmd === "sync") {
  const body = `// GENERATED by \`node scripts/brands.mjs sync\` —— 别手改，改 brands/library.json\n` +
    `// 只包含 public/brands/ 里文件真的存在的牌子；缺文件的条目上屏会让 Remotion 报缺静态文件\n` +
    `export type Brand = { key: string; label: string; file: string; aliases: string[] };\n\n` +
    `export const BRANDS: Brand[] = ${JSON.stringify(live, null, 1).replace(/\n/g, "\n")};\n`;
  fs.writeFileSync(OUT, body);
  console.log(`✓ src/lib/brands.generated.ts：${live.length} 个牌子可用`);
  if (missing.length) console.log(`  还没放文件的 ${missing.length} 个：${missing.map((e) => `${e.label}(${e.file})`).join("、")}`);
  if (broken.length) console.log(`  ⚠ 文件在但只有 ${broken.map((e) => `${e.file}=${sizeOf(e)}B`).join("、")}：太小/空文件不算 logo，重新下载或换成 ≥200px 的透明底 png`);
  if (unmapped.length) console.log(`  public/brands/ 里没登记的 ${unmapped.length} 个文件：${unmapped.join("、")}（去 brands/library.json 补一条）`);
  process.exit(0);
}

if (cmd === "missing") {
  for (const e of missing) console.log(`${e.key}\t${e.label}\t需要 public/brands/${e.file}\t文案叫法：${e.aliases.join("/")}`);
  if (!missing.length) console.log("（全部牌子的文件都已就位）");
  process.exit(0);
}

console.log(`牌子清单 ${entries.length} 个：${live.length} 个有文件、${missing.length} 个缺文件`);
for (const e of live) console.log(`  ✓ ${e.label.padEnd(14)} public/brands/${e.file}`);
for (const e of missing) console.log(`  · ${e.label.padEnd(14)} 缺 public/brands/${e.file}（文案里可能叫：${e.aliases.join(" / ")}）`);
if (unmapped.length) console.log(`\npublic/brands/ 里有 ${unmapped.length} 个没登记的文件：${unmapped.join("、")}`);
console.log(`\n改完跑：node scripts/brands.mjs sync`);

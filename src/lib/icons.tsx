// pick a sensible icon from a Chinese label (封面 -> image, 正文 -> doc ...)
export const guessIcon = (label: string): string | undefined => {
  const rules: [RegExp, string][] = [
    [/封面|图片|截图|海报/, "image"],
    [/正文|文案|文本|文档|讲稿|脚本/, "doc"],
    [/标签|话题|#/, "hash"],
    [/分镜|剪辑|镜头/, "film"],
    [/口播|成片|视频|录屏/, "video"],
    [/配音|声音|语音/, "mic"],
    [/搜索|检索|查/, "search"],
    [/浏览器|网页|页面/, "browser"],
    [/数据|分析|报表|排行/, "chart"],
    [/评论|留言|私信/, "chat"],
    [/下载/, "download"],
    [/粉丝|用户|人/, "users"],
    [/时间|分钟|小时|秒/, "clock"],
    [/自动|AI|智能/, "bot"],
    [/需求|痛点|目标|精准/, "target"],
    [/爆款|热门|流量|火/, "fire"],
    [/增长|上涨|翻倍|提升|收入/, "up"],
    [/下降|下滑|掉/, "down"],
    [/订单|成交|奖|变现|钱/, "award"],
    [/工具|方法|技巧/, "tool"],
    [/内容|作品/, "layers"],
  ];
  for (const [re, n] of rules) if (re.test(label)) return n;
  return undefined;
};
